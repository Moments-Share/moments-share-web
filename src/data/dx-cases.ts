/* ============================================================
   DX・AX支援の事例。
   /service-dx/ に並ぶ。空のあいだはセクションごと出ないので、
   1件できたら下の配列に足すだけでページに現れる。

   書き方の約束：
   ・社名を出せないときは client を「製造業A社（西尾市）」のように書く。
     業種と地域だけでも、読む人は自分に当てはめられる。
   ・before / after は、できるだけ数字で書く。
     「効率化しました」では何も伝わらない。
   ・kind は、やり方を変えずに速くしたなら "DX"、
     仕事の組み立てから変えたなら "AX"。
   ・数字は必ず実測値にする。試算を載せるときは note に
     「試算」と書く（ページ内の他の試算と同じ扱いにする）。
   ============================================================ */

export type DxCase = {
  /** 社名、または「製造業A社（西尾市）」のような伏せ字 */
  client: string;
  kind: "DX" | "AX";
  /** 何をした仕事か。20字程度 */
  title: string;
  /** 手をつける前の状態。数字があれば数字で */
  before: string;
  /** 変わったあと。数字があれば数字で */
  after: string;
  /** 使った道具。「ChatGPT / GAS」のように */
  tools?: string;
  /** 補足。試算のときはここに明記する */
  note?: string;
};

export const dxCases: DxCase[] = [];
